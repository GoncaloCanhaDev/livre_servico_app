/// The sheet's absence codes and their names.
const defaultHorarioAusencias = {
  'FO': 'Folga',
  'F': 'Férias',
  'A': 'Ausência',
  'LP': 'Parentalidade',
};

/// [_codigos] read into [HorarioCodigo]s.
Map<String, HorarioCodigo> defaultHorarioCodigos() => {
  for (final e in _codigos.entries)
    e.key: HorarioCodigo.fromJson(e.key, switch (e.value.split(' ')) {
      [final entrada, final saida] => {'entrada': entrada, 'saida': saida},
      [final entrada, final pausa, final saida] => {
        'entrada': entrada,
        'pausa': pausa,
        'saida': saida,
      },
      _ => throw StateError('Código ${e.key} mal escrito.'),
    }),
};
